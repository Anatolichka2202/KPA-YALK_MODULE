def set_font(run, size=10.5, bold=None, color="000000", italic=False):
    name = "Arial"
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    rpr.rFonts.set(qn("w:ascii"), name)
    rpr.rFonts.set(qn("w:hAnsi"), name)
    rpr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor.from_string(color)


def add_text(p, text, *, size=10.5, bold=False, color="000000", italic=False):
    r = p.add_run(text)
    set_font(r, size=size, bold=bold, color=color, italic=italic)
    return r


def para(doc, text="", *, before=0, after=5, line=1.1, keep=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = line
    p.paragraph_format.keep_with_next = keep
    if text:
        add_text(p, text)
    return p


def bullet(doc, text, level=0):
    p = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.08
    add_text(p, text)
    return p


def numbered(doc, text):
    p = doc.add_paragraph(style="List Number")
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.08
    add_text(p, text)
    return p


def shade(cell, fill):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = tcpr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tcpr.append(shd)
    shd.set(qn("w:fill"), fill)


def cell_margins(cell, top=105, start=115, bottom=105, end=115):
    tcpr = cell._tc.get_or_add_tcPr()
    mar = tcpr.first_child_found_in("w:tcMar")
    if mar is None:
        mar = OxmlElement("w:tcMar")
        tcpr.append(mar)
    for name, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        el = mar.find(qn(f"w:{name}"))
        if el is None:
            el = OxmlElement(f"w:{name}")
            mar.append(el)
        el.set(qn("w:w"), str(value))
        el.set(qn("w:type"), "dxa")


def borders(cell, color=LIGHT_BORDER):
    tcpr = cell._tc.get_or_add_tcPr()
    bd = tcpr.first_child_found_in("w:tcBorders")
    if bd is None:
        bd = OxmlElement("w:tcBorders")
        tcpr.append(bd)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = bd.find(qn(f"w:{edge}"))
        if el is None:
            el = OxmlElement(f"w:{edge}")
            bd.append(el)
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "6")
        el.set(qn("w:color"), color)
        el.set(qn("w:space"), "0")


def repeat_header(row):
    trpr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trpr.append(el)


def set_widths(table, widths):
    for row in table.rows:
        for i, width in enumerate(widths):
            row.cells[i].width = Cm(width)


def format_table(table, widths, *, font_size=8.8, centers=None, status_col=None):
    centers = centers or set()
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    repeat_header(table.rows[0])
    set_widths(table, widths)
    for ri, row in enumerate(table.rows):
        for ci, cell in enumerate(row.cells):
            borders(cell)
            cell_margins(cell)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if ri == 0:
                shade(cell, NAVY)
            elif ri % 2 == 0:
                shade(cell, PALE_GRAY)
            if status_col is not None and ri > 0 and ci == status_col:
                value = cell.text.upper()
                if "ГОТОВО" in value or "ПРИНЯТО" in value:
                    shade(cell, PALE_GREEN)
                elif "БЛОК" in value or "НЕ ПОКРЫТО" in value:
                    shade(cell, PALE_RED)
                else:
                    shade(cell, PALE_AMBER)
            for p in cell.paragraphs:
                p.paragraph_format.space_after = Pt(0)
                p.paragraph_format.line_spacing = 1.02
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER if ri == 0 or ci in centers else WD_ALIGN_PARAGRAPH.LEFT
                for r in p.runs:
                    set_font(r, size=font_size, bold=(ri == 0), color=("FFFFFF" if ri == 0 else "000000"))


def add_table(doc, headers, rows, widths, *, font_size=8.8, centers=None, status_col=None):
    t = doc.add_table(rows=1, cols=len(headers))
    for i, h in enumerate(headers):
        t.rows[0].cells[i].text = h
    for data in rows:
        cells = t.add_row().cells
        for i, value in enumerate(data):
            cells[i].text = str(value)
    format_table(t, widths, font_size=font_size, centers=centers, status_col=status_col)
    return t


def add_page_number(p):
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    r = p.add_run("Страница ")
    set_font(r, size=8.5, color=MID_GRAY)
    start = OxmlElement("w:fldChar")
    start.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    r._r.extend([start, instr, end])


